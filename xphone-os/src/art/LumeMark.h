inline void drawLumeMark(Gfx& gfx, const int centerX, const int topY, const int requestedSize) {
  const int size = requestedSize >= 48 ? 120 : 24;
  const uint8_t* bmp = requestedSize >= 48 ? kLumeMark120x120 : kLumeMark24x24;
  const int leftX = centerX - size / 2;
  const int rowBytes = (size + 7) / 8;

  for (int r = 0; r < size; ++r) {
    for (int c = 0; c < size; ++c) {
      const uint8_t byteVal = bmp[r * rowBytes + (c >> 3)];
      if (((byteVal >> (7 - (c & 7))) & 1) == 0) {
        gfx.drawPixel(leftX + c, topY + r, true);
      }
    }
  }
}
